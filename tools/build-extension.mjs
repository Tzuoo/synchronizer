import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

export const extensionRoot = new URL('../../RuntimeData/同步器擴充功能/', import.meta.url);
// Preserve the original script order: function declarations share one scope,
// and startup calls must not be moved across state initialization.
export const contentParts = Object.freeze([
  'shared.js',
  'parsers-dom.js',
  'parsers-umh.js',
  'parsers-a06.js',
  'parsers-amc.js',
  'parsers-gateway.js',
  'ledger.js',
  'sync.js',
  'frames.js',
]);

export async function composeContent(root = extensionRoot) {
  const parts = await Promise.all(contentParts.map(async name => {
    const source = (await readFile(new URL(`src/content/${name}`, root), 'utf8')).replace(/\r\n/g, '\n');
    return `// ---- src/content/${name} ----\n${source.trimEnd()}\n`;
  }));
  const source = '// Generated by tools/build-extension.mjs. Edit src/content/*, not this file.\n\n' + parts.join('\n');
  new vm.Script(source, { filename: 'content.js' });
  return source;
}

export async function buildContent({ root = extensionRoot, check = false } = {}) {
  const source = await composeContent(root);
  const target = new URL('content.js', root);
  if (check) {
    const actual = (await readFile(target, 'utf8')).replace(/\r\n/g, '\n');
    if (actual !== source) throw new Error('content.js is stale. Run node tools/build-extension.mjs before testing or packaging.');
  } else {
    await writeFile(target, source, 'utf8');
  }
  return source;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildContent({ check: process.argv.includes('--check') });
  console.log(process.argv.includes('--check') ? 'Extension content bundle is current.' : 'Extension content bundle generated.');
}
